def li(d, t, desc, who, st):
    lab, cls = STATE[st]
    sty = ' style="color:#e0b46a;border-color:#e0b46a"' if st == 'ask' else ''
    return (f'<li><span class="d">{e(d)}</span><span class="m"><b>{e(t)}</b><em>{e(desc)}</em>'
            f'<em style="color:var(--muted)">{e(who)}</em></span><span class="chip{cls}"{sty}>{e(lab)}</span></li>')

def build():
    now = ''.join(f'<li><span class="n">{"✓" if s == "done" else "·"}</span><span class="t"><b>{e(a)}</b><span style="display:block;font-size:13px;color:var(--muted)">{e(b)}</span></span>'
                  f'<span class="chip{STATE[s][1]}"{" style=\"color:#e0b46a;border-color:#e0b46a\"" if s == "ask" else ""}>{STATE[s][0]}</span></li>' for s, a, b in NOW)
    out = [f'\n    <div class="tip">{TIP}</div>\n',
           f'    <h2>지금 상태<small>10/24 기준</small></h2>\n    <ol class="topics">{now}</ol>\n']
    for h, sm, items in PHASES:
        out.append(f'    <h2>{e(h)}<small>{e(sm)}</small></h2>\n    <ol class="plan subplan">{"".join(li(*x) for x in items)}</ol>\n')
    out.append('    <div class="note">' + ''.join(f'<div><b>{e(a)}:</b> {e(b)}</div>' for a, b in NOTES) + '</div>\n  ')
    return ''.join(out)

