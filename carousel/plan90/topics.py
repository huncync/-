def chip(s, k):
    if not s: return '<span></span>'
    cls = {'done': ' done', 'top': ' top'}.get(k, '')
    sty = ' style="color:#e07a7a;border-color:#e07a7a"' if k == 'bad' else ''
    return f'<span class="chip{cls}"{sty}>{e(s)}</span>'

def build():
    mx = max(s[1] for s in SCORE)
    sc = ''.join(
        f'<li><span class="n">{e(f)}</span><span class="t"><span style="display:block;height:6px;border-radius:3px;background:var(--line);overflow:hidden;margin:2px 0 6px">'
        f'<i style="display:block;height:100%;width:{round(v / mx * 100)}%;background:{"#e07a7a" if k == "bad" else "var(--gold)"}"></i></span>'
        f'<span style="font-size:12px;color:var(--muted)">{e(src)}</span></span><span class="chip{" top" if k == "top" else ""}"{" style=\"color:#e07a7a;border-color:#e07a7a\"" if k == "bad" else ""}>평균 {v:g}만</span></li>'
        for f, v, src, k in SCORE)
    out = [f'\n    <div class="tip">{TIP}</div>\n',
           f'    <h2>형식별 성적<small>10/24 16시 기준 · 올린 지 하루 이하인 편도 포함이라 참고용</small></h2>\n    <ol class="topics">{sc}</ol>\n']
    for h, sm, lead, items in SEC:
        li = ''.join(f'<li><span class="n">{e(n)}</span><span class="t">{e(t)}</span>{chip(s, k)}</li>' for n, t, s, k in items)
        out.append(f'    <h2>{e(h)}<small>{e(sm)}</small></h2>\n    <p class="lead">{e(lead)}</p>\n    <ol class="topics">{li}</ol>\n')
    out.append('    <div class="note">' + ''.join(f'<div><b>{e(a)}:</b> {e(b)}</div>' for a, b in RULES) + '</div>\n  ')
    return ''.join(out)

if __name__ == '__main__':
    P = sys.argv[1]
    t = open(P, encoding='utf-8').read()
    a = t.index('<section class="panel" id="p-topics"'); a2 = t.index('>', a) + 1; b = t.index('</section>', a)
    t = t[:a2] + build() + t[b:]
    open(P, 'w', encoding='utf-8').write(t)
    print('ok', sum(len(s[3]) for s in SEC), 'topics')
